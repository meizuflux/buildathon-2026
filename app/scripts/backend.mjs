import { spawn } from 'node:child_process';
import { existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const python = process.platform === 'win32' ? resolve(root, 'backend/.venv/Scripts/python.exe') : resolve(root, 'backend/.venv/bin/python');
if (!existsSync(python)) throw new Error('Run uv sync --project backend --locked --python 3.14 from the repository root first.');
mkdirSync(resolve(root, '.runtime'), { recursive: true });
const env = { ...process.env, DATABASE_PATH: process.env.DATABASE_PATH ?? resolve(root, '.runtime/haven.sqlite3') };
const seed = process.argv.includes('--seed');
const args = seed ? ['-c', 'import asyncio; from haven.demo_data import main; asyncio.run(main())'] : ['-m', 'uvicorn', 'backend_dev:app', '--app-dir', resolve(root, 'app/scripts'), '--host', process.env.HOST ?? '0.0.0.0', '--port', process.env.PORT ?? '8000', '--no-proxy-headers'];
const child = spawn(python, args, { cwd: root, env, stdio: 'inherit', windowsHide: true });
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
child.on('exit', code => { process.exitCode = code ?? 0; });
process.on('SIGINT', () => child.kill('SIGINT'));
