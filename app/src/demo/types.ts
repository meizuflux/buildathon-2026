// Types for the resident dashboard demo. Kept separate from UI so the recommendation rules can be
// tested without React.

/** A household answer that may be unknown ("Not sure"). */
export type Answer = 'yes' | 'no' | 'unknown';

/** What a shelter has reported about one capability. */
export type CapabilityState = 'confirmed' | 'not_available' | 'unknown';

export type Requirement = 'wheelchairEntrance' | 'dogs' | 'children' | 'poweredEquipment';

export interface DemoHousehold {
  id: string;
  name: string;
  adults: number;
  children: number;
  childAges: number[];
  dogs: number;
  petNote: string;
  wheelchairEntrance: Answer;
  poweredEquipment: Answer;
  vehicle: Answer;
  transportHelp: Answer;
  location: { label: string; lat: number; lng: number };
}

export interface Capability {
  state: CapabilityState;
  /** What exactly was reported, in plain language. */
  detail: string;
  /** Simulation minute the report was made. */
  reportedAt: number;
}

export interface Route {
  id: string;
  via: string;
  minutes: number;
  /** Roads the illustrative route uses; a closure on any of them blocks the route. */
  roads: string[];
  /** Illustrative path for the map. Not navigable road geometry. */
  path: [number, number][];
}

export interface DemoShelter {
  id: string;
  name: string;
  address: string;
  operator: string;
  lat: number;
  lng: number;
  status: 'open' | 'closed';
  /** Spaces reported available, or null when not reported. */
  spaces: number | null;
  spacesReportedAt: number;
  capabilities: Record<Requirement, Capability>;
  routes: Route[];
}

export interface Closure {
  id: string;
  road: string;
  label: string;
  reason: string;
  authority: string;
  at: number;
  point: [number, number];
}

export interface OfficialInstruction {
  id: string;
  level: 'mandatory' | 'advisory';
  headline: string;
  details: string;
  authority: string;
  issuedAt: number;
}

export interface Broadcast {
  id: string;
  title: string;
  body: string;
  authority: string;
  severity: 'critical' | 'attention' | 'info';
  at: number;
}

export type MessageState = 'sending' | 'sent' | 'failed';

export interface Message {
  id: string;
  from: 'household' | 'coordinator';
  author: string;
  role: string;
  body: string;
  at: number;
  state?: MessageState;
  /** Coordinator replies generated by the demo are always simulated. */
  simulated?: boolean;
}

export interface SystemNotice {
  id: string;
  at: number;
  title: string;
  lines: string[];
}

/** One requirement checked against one shelter. */
export interface RequirementCheck {
  requirement: Requirement;
  /** Whether the household needs it: required, possibly (household answered "Not sure"), or not needed. */
  need: 'required' | 'possibly';
  state: CapabilityState;
  label: string;
  detail: string;
}

export interface ShelterAssessment {
  shelter: DemoShelter;
  checks: RequirementCheck[];
  route: Route | null;
  /** Roads closed on the preferred route, when the shelter was rerouted. */
  rerouted: boolean;
  spacesOk: boolean | null;
  /** Reasons the shelter cannot be used at all. */
  blockers: string[];
  /** Things that could not be confirmed. */
  unresolved: string[];
  eligible: boolean;
  verified: boolean;
}

export interface Recommendation {
  /** recommended: a verified fit. unverified: best option still has unconfirmed requirements. none: nothing usable. */
  status: 'recommended' | 'unverified' | 'none';
  destination: ShelterAssessment | null;
  alternatives: { assessment: ShelterAssessment; whyNot: string }[];
  /** Household-side unknowns that affect the choice. */
  householdUnknowns: string[];
  /** The household already left; the destination was kept even if conditions changed. */
  keptBecauseTravelling: boolean;
  advisory: string | null;
}
